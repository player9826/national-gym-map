const { _electron: electron, expect } = require("@playwright/test");
const fs = require("node:fs"), path = require("node:path"), os = require("node:os"), assert = require("node:assert/strict");
const { Store } = require("../electron/storage.cjs");
const catalog = require("../electron/catalog.cjs");
(async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "gym-form-152-"));
  const profile = path.join(temp, "profile");
  const store = new Store(path.join(profile, "location.json"));
  store.configure(path.join(temp, "data"));
  catalog.upsert(store, "equipment", { name: "系列测试单车", brandId: "brand-1", equipmentType: "cardio", series: "Series One" });
  catalog.upsert(store, "equipment", { name: "另一品牌单车", brandId: "brand-2", equipmentType: "cardio", series: "Series Two" });
  const checks = [], errors = [];
  const app = await electron.launch({ args: ["."], env: { ...process.env, GYM_TEST_PROFILE: profile } });
  try {
    const page = await app.firstWindow();
    page.on("pageerror", error => errors.push(error.message));
    await app.evaluate(({ app }) => {
      const { handlers } = process.mainModule.require(process.mainModule.require("node:path").join(app.getAppPath(), "electron/main.cjs"));
      global.form152Saves = [];
      handlers.saveEquipment = row => { global.form152Saves.push(row); return { ...row, id: "fixture-save" }; };
    });
    await page.getByRole("button", { name: "器械库", exact: true }).click();
    await page.getByRole("button", { name: "新增器械", exact: true }).first().click();
    let dialog = page.getByRole("dialog", { name: "新增器械", exact: true });
    await dialog.getByLabel("品牌", { exact: false }).first().selectOption("brand-1");
    await expect(dialog.locator("#equipment-series-suggestions option")).toHaveAttribute("value", "Series One");
    await dialog.getByLabel("系列（可留空）").fill("New Series");
    await dialog.getByLabel("品牌", { exact: false }).first().selectOption("brand-2");
    await expect(dialog.getByLabel("系列（可留空）")).toHaveValue("");
    await expect(dialog.locator("#equipment-series-suggestions option")).toHaveAttribute("value", "Series Two");
    await dialog.getByLabel("器械名称", { exact: false }).fill("颈部训练器");
    await dialog.getByLabel("器械类型", { exact: true }).selectOption("fixed");
    await dialog.getByLabel("其他", { exact: true }).check();
    await dialog.getByLabel("其他部位名称", { exact: true }).fill("颈部");
    await dialog.getByRole("button", { name: "添加部位", exact: true }).click();
    await expect(dialog.getByLabel("颈部", { exact: true })).toBeChecked();
    await dialog.getByRole("button", { name: "保存器械", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    let saves = await app.evaluate(() => global.form152Saves);
    assert.deepEqual(saves[0].parts, ["CUSTOM:颈部"]);
    assert.deepEqual(saves[0].tags, []);
    checks.push("brand scoped series suggestions and reset; custom-only part saves without application tags");
    await page.getByRole("button", { name: "新增器械", exact: true }).first().click();
    dialog = page.getByRole("dialog", { name: "新增器械", exact: true });
    await dialog.getByLabel("品牌", { exact: false }).first().selectOption("brand-1");
    await dialog.getByLabel("器械名称", { exact: false }).fill("肩手臂腿部组合器");
    await dialog.getByLabel("器械类型", { exact: true }).selectOption("fixed");
    await dialog.getByLabel("肩", { exact: true }).check();
    await dialog.getByRole("button", { name: "保存器械", exact: true }).click();
    await expect(dialog.getByRole("alert")).toContainText("至少选择一个部位及对应应用标签");
    await dialog.getByLabel("推肩", { exact: true }).check();
    await expect(dialog.getByLabel("肩推", { exact: true })).toHaveCount(0);
    await dialog.getByLabel("手臂", { exact: true }).check();
    await dialog.getByLabel("小臂", { exact: true }).check();
    await dialog.getByLabel("腿", { exact: true }).check();
    await dialog.getByLabel("小腿", { exact: true }).check();
    await dialog.getByRole("button", { name: "保存器械", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    saves = await app.evaluate(() => global.form152Saves);
    assert.deepEqual(saves[1].tags, ["肩推", "小臂", "小腿"]);
    checks.push("built-in parts require tags; push-shoulder display preserves stored key; forearm and calf tags selected");
    assert.deepEqual(errors, []);
  } finally {
    await app.close();
    fs.mkdirSync("test-results", { recursive: true });
    fs.writeFileSync("test-results/classification-form-152.json", JSON.stringify({ checks, errors, temp, note: "UI save payload assertions use a mocked save handler." }, null, 2));
  }
  console.log(JSON.stringify({ checks, errors }));
})().catch(error => { console.error(error); process.exitCode = 1; });
