test('upstream deletion retains subscriber data and subscriptions persist through restart', async t => {
  const { publisher, subscriber, publish, api, preview } = fixture(t);
  const draft = await preview(); await api.sharedApply({ token: draft.token });
  const restarted = new Store(subscriber.configFile);
  assert.equal(Object.keys(restarted.db.metadata.sharedCatalogs).length, 1);
  publisher.save({ ...publisher.db, gyms: [], links: [] }); publish();
  const next = await preview(); await api.sharedApply({ token: next.token });
  assert.equal(subscriber.db.gyms.length, 1);
  assert.equal(subscriber.db.links.length, 1);
});
test('existing hash-matched images are reused and failed database save rolls new images back', async t => {
  const { subscriber, api, preview } = fixture(t);
  let draft = await preview();
  assert.equal(draft.downloadImages, 1);
  const save = subscriber.save.bind(subscriber);
  subscriber.save = () => { throw new Error('disk full'); };
  await assert.rejects(api.sharedApply({ token: draft.token }), /disk full/);
  assert.equal(subscriber.db.gyms.length, 0);
  assert.equal(fs.readdirSync(path.join(subscriber.root, 'gyms')).length, 0);
  subscriber.save = save;
  draft = await preview(); await api.sharedApply({ token: draft.token });
  draft = await preview();
  assert.equal(draft.images, 1);
  assert.equal(draft.downloadImages, 0);
});
