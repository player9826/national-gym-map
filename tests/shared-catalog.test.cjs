const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { Store, hash } = require('../electron/storage.cjs');
const { exportShared, createSharedCatalog } = require('../electron/shared-catalog.cjs');
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'gym-shared-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const publisher = new Store(path.join(root, 'publisher.json'));
  const subscriber = new Store(path.join(root, 'subscriber.json'));
  publisher.configure(path.join(root, 'source'));
  subscriber.configure(path.join(root, 'target'));
  const db = structuredClone(publisher.db);
  db.gyms.push({ id: 'gym1', name: 'Public gym', city: '上海', lat: null, lng: null, visited: true, visitDate: '2026-01-01', description: 'PRIVATE', notes: 'PRIVATE', reviewUrl: 'https://private.test', brandIds: ['brand-1'], cover: 'gyms/cover.png', photos: [] });
  db.equipment.push({ id: 'eq1', name: 'Bike', brandId: 'brand-1', equipmentType: 'cardio', parts: [], tags: [], notes: 'PRIVATE', image: '' });
  db.links.push({ id: 'link1', gymId: 'gym1', equipmentId: 'eq1', quantity: 2 });
  publisher.save(db);
  fs.mkdirSync(path.join(publisher.root, 'gyms'));
  fs.writeFileSync(path.join(publisher.root, 'gyms/cover.png'), Buffer.from([137, 80, 78, 71, 1]));
  const destination = path.join(root, 'public');
  const publish = () => exportShared(publisher, { destination, includeImages: true });
  publish();
  const fetcher = async url => fs.readFileSync(path.join(destination, new URL(url).pathname.replace('/repo/', '')));
  const api = createSharedCatalog(subscriber, fetcher);
  const preview = () => api.sharedPreview({ url: 'https://example.test/repo/manifest.json' });
  return { publisher, subscriber, destination, publish, api, preview };
}
