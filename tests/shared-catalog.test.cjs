test('classification merges as one unit when local and publisher change different classification fields', async t => {
  const { publisher, subscriber, publish, api, preview } = fixture(t);
  let db = structuredClone(publisher.db);
  Object.assign(db.equipment[0], { equipmentType: 'fixed', parts: ['CHEST'], part: 'CHEST', tags: ['推胸'], loading: '' });
  publisher.save(db); publish();
  let draft = await preview(); await api.sharedApply({ token: draft.token });
  db = structuredClone(subscriber.db);
  Object.assign(db.equipment[0], { equipmentType: 'free_weight', freeWeightType: 'dumbbell', parts: [], part: '', tags: [], loading: '' });
  subscriber.save(db);
  db = structuredClone(publisher.db); db.equipment[0].tags.push('夹胸');
  publisher.save(db); publish();
  draft = await preview();
  assert.ok(draft.conflicts.some(c => c.field === 'classification'));
  await api.sharedApply({ token: draft.token });
  assert.equal(subscriber.db.equipment[0].equipmentType, 'free_weight');
  assert.equal(subscriber.db.equipment[0].freeWeightType, 'dumbbell');
  assert.deepEqual(subscriber.db.equipment[0].parts, []);
  assert.deepEqual(subscriber.db.equipment[0].tags, []);
});
test('existing export directory retains publisher identity and rejects different publishers', t => {
  const { publisher, destination } = fixture(t);
  const originalId = publisher.db.metadata.sharedPublisherId;
  const db = structuredClone(publisher.db); delete db.metadata.sharedPublisherId;
  publisher.save(db);
  assert.equal(exportShared(publisher, { destination }).sourceId, originalId);
  assert.equal(publisher.db.metadata.sharedPublisherId, originalId);
  publisher.save({ ...publisher.db, metadata: { ...publisher.db.metadata, sharedPublisherId: 'another-publisher' } });
  assert.throws(() => exportShared(publisher, { destination }), /其他共享库/);
  assert.equal(JSON.parse(fs.readFileSync(path.join(destination, 'manifest.json'))).sourceId, originalId);
});
