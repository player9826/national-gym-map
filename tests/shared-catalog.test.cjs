test('preview does not write; confirmed subscription maps ids and preserves three-way local changes', async t => {
  const { publisher, subscriber, publish, api, preview } = fixture(t);
  const before = JSON.stringify(subscriber.db);
  let draft = await preview();
  assert.equal(JSON.stringify(subscriber.db), before);
  assert.equal(draft.counts.added, 3);
  await api.sharedApply({ token: draft.token });
  const localId = subscriber.db.gyms[0].id;
  assert.notEqual(localId, 'gym1');
  assert.equal(subscriber.db.gyms[0].visited, false);
  assert.equal(subscriber.db.brands.length, 19);
  let db = structuredClone(subscriber.db);
  db.gyms[0].visited = true; db.gyms[0].description = 'personal'; db.gyms[0].name = 'local edit';
  subscriber.save(db);
  db = structuredClone(publisher.db);
  db.gyms[0].name = 'remote edit'; db.gyms[0].city = '北京';
  publisher.save(db); publish();
  draft = await preview();
  assert.ok(draft.counts.conflicts >= 1);
  await api.sharedApply({ token: draft.token });
  assert.equal(subscriber.db.gyms[0].name, 'local edit');
  assert.equal(subscriber.db.gyms[0].city, '北京');
  assert.equal(subscriber.db.gyms[0].description, 'personal');
  assert.equal(subscriber.db.gyms[0].visited, true);
  assert.equal(subscriber.db.gyms[0].id, localId);
  draft = await preview();
  assert.equal(draft.counts.added, 0);
});
